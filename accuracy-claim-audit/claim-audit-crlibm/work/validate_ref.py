"""Validation of the audit reference (work/ref.py).

Part 1: to_double() against an exact Fraction oracle.
Part 2: the whole reference against crlibm's own tests/*.testdata vectors,
        which were generated by the crlibm authors with MPFR.
Part 3: a few analytic values per function.
"""
import sys, os, struct, random
from fractions import Fraction as F

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import gmpy2
from gmpy2 import mpfr
import ref

TWO = F(2)


def frac_to_double(r, mode):
    """Exact oracle: round Fraction r to the nearest/up/down/zero double.

    Uses CPython's own correctly-rounded Fraction->float conversion (round to
    nearest, ties to even) as the base, then moves one ulp for the directed
    modes when the conversion lost information.  Independent of MPFR.
    """
    import math
    if r == 0:
        return 0.0
    rn = float(r)                      # correctly rounded by CPython
    if mode == "rn":
        return rn
    exact_is_rn = (F(rn) == r)
    if mode == "ru":
        if exact_is_rn or r < rn:
            return rn
        return math.nextafter(rn, math.inf)
    if mode == "rd":
        if exact_is_rn or r > rn:
            return rn
        return math.nextafter(rn, -math.inf)
    if mode == "rz":
        if exact_is_rn:
            return rn
        return rn if r > 0 and r > rn else (
            rn if r < 0 and r < rn else math.nextafter(rn, 0.0))
    raise ValueError(mode)


DBL_MAX_F = F(2 ** 1024) - F(2 ** 971)          # largest finite double
OVF_MID_F = F(2 ** 1024) - F(2 ** 970)          # RNDN overflow threshold
DBL_MAX_D = float.fromhex("0x1.fffffffffffffp+1023")


def oracle_big(r, mode):
    """Exact rounding of a huge positive rational, IEEE overflow rules."""
    import math
    inf = math.inf
    if r <= DBL_MAX_F:
        return None
    if r >= F(2 ** 1024):
        return inf if mode in ("rn", "ru") else DBL_MAX_D
    if mode == "ru":
        return inf
    if mode in ("rd", "rz"):
        return DBL_MAX_D
    return DBL_MAX_D if r < OVF_MID_F else inf


def overflow_boundary(rndmap):
    """The overflow threshold is where a reference is most likely to be wrong."""
    cases = [DBL_MAX_F - 1, DBL_MAX_F, DBL_MAX_F + 1, OVF_MID_F - 1,
             OVF_MID_F, OVF_MID_F + 1, F(2 ** 1024) - 1, F(2 ** 1024),
             F(2 ** 1024) + 1]
    bad = 0
    for r in cases:
        for s in (1, -1):
            rr = r * s
            for mode, gmode in rndmap.items():
                # by symmetry: rounding a negative value up means rounding its
                # magnitude down, and vice versa
                mag_mode = mode if s > 0 else {"rn": "rn", "ru": "rd",
                                               "rd": "ru", "rz": "rz"}[mode]
                want = oracle_big(abs(rr), mag_mode)
                if want is None:
                    continue
                want = want if s > 0 else -want
                # these magnitudes need ~1025 bits to be exact
                with gmpy2.context(precision=1100, round=ref.RNDN):
                    v = mpfr(rr.numerator) / mpfr(rr.denominator)
                got = ref.to_double(v, gmode)
                if struct.pack(">d", got) != struct.pack(">d", want):
                    bad += 1
                    print("  OVF MISMATCH", mode, s, r, "want", want,
                          "got", got)
    print("part1a: overflow boundary, mismatches:", bad,
          "of", len(cases) * 2 * 4)
    return bad


def part1(trials=4000, seed=7):
    rnd = random.Random(seed)
    rndmap = {"rn": ref.RNDN, "ru": ref.RNDU, "rd": ref.RNDD, "rz": ref.RNDZ}
    bad = 0
    bad += overflow_boundary(rndmap)
    trials -= 1
    for i in range(trials):
        kind = i % 5
        if kind == 0:                  # subnormal region
            r = F(rnd.randrange(1, 2 ** 52), 2 ** 1074) * rnd.choice([1, -1])
        elif kind == 1:                # random dyadic in the normal range
            r = F(rnd.randrange(1, 2 ** 60), 2 ** rnd.randrange(1, 60)) \
                * rnd.choice([1, -1])
        elif kind == 2:                # exactly halfway between two doubles
            k = rnd.randrange(1, 2 ** 52) * 2 + 1
            r = F(k, 2 ** 1075)
        elif kind == 3:                # halfway in the subnormal region
            r = F(rnd.randrange(1, 2 ** 51) * 2 + 1, 2 ** 1075)
        else:                          # tiny dyadics, near the underflow edge
            r = F(1, 2 ** rnd.randrange(1060, 1120))
        exp = frac_to_double(r, "rn")
        if exp is None:
            continue
        for mode, gmode in rndmap.items():
            want = frac_to_double(r, mode)
            if want is None:
                continue
            p = max(64, r.denominator.bit_length() + r.numerator.bit_length())
            with gmpy2.context(precision=p, round=ref.RNDN):
                v = mpfr(r.numerator) / mpfr(r.denominator)
            assert F(v) == r, (r, v)
            got = ref.to_double(v, gmode)
            if struct.pack(">d", got) != struct.pack(">d", want):
                bad += 1
                if bad < 6:
                    print("  MISMATCH", mode, r, "want", want.hex(), "got", got.hex())
    print("part1: to_double vs exact Fraction oracle, mismatches:", bad,
          "of", trials, "trials")
    return bad


def words_to_hex(w1, w2):
    return w1 + w2


def part2(datadir, funcs=None, limit=None):
    totals = {}
    files = sorted(f for f in os.listdir(datadir) if f.endswith(".testdata"))
    for fn in files:
        name = fn[:-len(".testdata")]
        if funcs and name not in funcs:
            continue
        if name in ("acospi", "asinpi", "atanpi", "pow"):
            continue                    # pow takes two args; *pi handled in part3
        import re
        hexpat = re.compile(r"^[0-9a-f]{8}$")
        mode = {"N": "rn", "P": "ru", "M": "rd", "Z": "rz"}
        n = ok = mismatch = undec = 0
        ex = []
        with open(os.path.join(datadir, fn)) as fh:
            for line in fh:
                line = line.split("#")[0].strip()
                if not line:
                    continue
                parts = line.split()
                if len(parts) != 5 or parts[0] not in mode:
                    continue
                if not all(hexpat.match(p) for p in parts[1:5]):
                    continue
                tag, i1, i2, o1, o2 = parts
                inhex, outhex = words_to_hex(i1, i2), words_to_hex(o1, o2)
                n += 1
                if limit and n > limit:
                    break
                rn, ru, rd, rz, st = ref.reference(name, inhex)
                if st != "decided":
                    undec += 1
                    continue
                got = {"rn": rn, "ru": ru, "rd": rd, "rz": rz}[mode[tag]]
                if got == outhex:
                    ok += 1
                else:
                    mismatch += 1
                    if len(ex) < 4:
                        ex.append((mode[tag], inhex, outhex, got))
        totals[name] = (n, ok, mismatch, undec)
        print("  %-8s n=%-6d agree=%-6d disagree=%-4d undecided=%-4d %s"
              % (name, n, ok, mismatch, undec, ex[:2] if ex else ""))
    return totals


def part3():
    """Analytic spot checks, one per function, independent of MPFR."""
    import math
    checks = [
        ("exp", "3ff0000000000000", None),      # e, cross-checked by mpmath below
        ("log", "4000000000000000", None),      # ln 2
        ("sinpi", "3ff0000000000000", "0000000000000000"),   # sin(pi)=+0
        ("cospi", "3ff0000000000000", "bff0000000000000"),   # cos(pi)=-1
        ("tanpi", "3ff0000000000000", "0000000000000000"),   # tan(pi)=+0
        ("sinpi", "3fe0000000000000", "3ff0000000000000"),   # sin(pi/2)=1
        ("cospi", "0000000000000000", "3ff0000000000000"),   # cos(0)=1
        ("expm1", "0000000000000000", "0000000000000000"),   # expm1(0)=0
        ("log1p", "0000000000000000", "0000000000000000"),   # log1p(0)=0
        ("sin", "0000000000000000", "0000000000000000"),     # sin(0)=+0
        ("cos", "0000000000000000", "3ff0000000000000"),     # cos(0)=1
        ("tan", "0000000000000000", "0000000000000000"),     # tan(0)=+0
        ("atan", "0000000000000000", "0000000000000000"),    # atan(0)=0
        ("atanpi", "0000000000000000", "0000000000000000"),  # atan(0)/pi=0
        ("sinh", "0000000000000000", "0000000000000000"),    # sinh(0)=+0
        ("cosh", "0000000000000000", "3ff0000000000000"),    # cosh(0)=1
        ("asin", "0000000000000000", "0000000000000000"),    # asin(0)=0
        ("acos", "3ff0000000000000", "0000000000000000"),    # acos(1)=0
        ("log2", "3ff0000000000000", "0000000000000000"),    # log2(1)=0
        ("log10", "3ff0000000000000", "0000000000000000"),   # log10(1)=0
    ]
    print("part3: analytic identities")
    bad = 0
    for func, inhex, want in checks:
        rn, ru, rd, rz, st = ref.reference(func, inhex)
        if want is None:
            print("  %-8s %s -> rn=%s (%s)" % (func, inhex, rn, st))
            continue
        status = "ok" if rn == want else "MISMATCH want " + want
        if rn != want:
            bad += 1
        print("  %-8s %s -> rn=%s %s" % (func, inhex, rn, status))
    return bad


