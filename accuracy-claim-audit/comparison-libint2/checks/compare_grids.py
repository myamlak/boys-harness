#!/usr/bin/env python3
"""Cross-check the two committed Boys reference grids at their common cells.

The accuracy-gate grid (tests/data/boys_accuracy_gate_reference.csv) carries 25
significant digits and was generated by tools/gen_boys_accuracy_gate_reference.py
at 80-digit mpmath precision.  The 45-digit grid (tests/data/boys_reference.csv)
was generated by tools/gen_boys_coefficients.py at 60-digit precision.  The two
generators share no code.  Where the two grids carry the same (n, x) cell, their
reference values must agree to the 25-digit grid's own precision; a disagreement
would mean a transcription or generation error in one of them.

Reads only the first three columns (n, x, value) and compares with Decimal, so
neither value is rounded to binary64 first.

Exit 0 when common cells exist and every one agrees within 1e-20 relative
(the 25-digit grid's worst representable agreement is ~5e-25); exit 1 otherwise.

The boys v5.3.2 checkout is taken from --boys, else BOYS_SOURCE, else a
checkout named ../boys beside the repository.
"""
import argparse
import csv
import decimal
import os
import sys
from pathlib import Path

parser = argparse.ArgumentParser()
parser.add_argument("--boys", default=os.environ.get(
    "BOYS_SOURCE",
    str(Path(__file__).resolve().parents[3].parent / "boys")))
args = parser.parse_args()
BOYS = Path(args.boys)

GATE = BOYS / "tests/data/boys_accuracy_gate_reference.csv"
GRID45 = BOYS / "tests/data/boys_reference.csv"

decimal.getcontext().prec = 80


def load(path):
    cells = {}
    with open(path, newline="") as handle:
        reader = csv.reader(handle)
        header = next(reader)
        if header[:3] != ["n", "x", "value"]:
            raise SystemExit(f"{path}: unexpected header {header[:3]}")
        for row in reader:
            if not row:
                continue
            n = int(row[0])
            x = row[1]
            value = decimal.Decimal(row[2])
            cells[(n, x)] = value
    return cells


gate = load(GATE)
grid45 = load(GRID45)

common = sorted(set(gate) & set(grid45))
if not common:
    print("no common (n, x) cells: nothing was cross-checked")
    raise SystemExit(1)

worst_abs = decimal.Decimal(0)
worst_abs_cell = None
worst_rel = decimal.Decimal(0)
worst_rel_cell = None
for key in common:
    a = gate[key]
    b = grid45[key]
    diff = abs(a - b)
    rel = diff / abs(b) if b != 0 else decimal.Decimal(0)
    if diff > worst_abs:
        worst_abs = diff
        worst_abs_cell = key
    if rel > worst_rel:
        worst_rel = rel
        worst_rel_cell = key

print(f"gate grid cells:      {len(gate)}")
print(f"45-digit grid cells:  {len(grid45)}")
print(f"common (n, x) cells:  {len(common)}")
print(f"worst absolute diff:  {worst_abs:.3E} at n={worst_abs_cell[0]}, x={worst_abs_cell[1]}")
print(f"worst relative diff:  {worst_rel:.3E} at n={worst_rel_cell[0]}, x={worst_rel_cell[1]}")
print("verdict: " + ("AGREE within 1e-20 relative" if worst_rel < decimal.Decimal("1e-20")
                      else "DISAGREE above 1e-20 relative"))
raise SystemExit(0 if worst_rel < decimal.Decimal("1e-20") else 1)
