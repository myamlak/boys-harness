#!/usr/bin/env python3
"""Emit Table S5, the distribution of the seed-against-fit ratio.

Reads

    sweeps/amplification_form/results/seed_fit_ratio.csv

which ``sweeps/amplification_form/seed_fit_ratio.py`` computes from the first
experiment's ``cells.csv`` and ``reference.csv``: one row per band and order
with the cell count and the quartiles of

    r = (|rec(0) - F_0(x)| / F_0(x)) / (|dir(n) - F_n(x)| / F_n(x))

over the cells at orders n >= 1 and x >= theta_n, plus a pooled row per band.

Writes ``tables/seed-fit-ratio.tex``: the rows of the longtable in Section S4
of the supplement, with a band column, the order, the cell count and the three
quartiles.  B1 has no cells at orders 17 to 32, because no B1 argument reaches
theta_17; those rows are omitted and the caption says so.  Cell counts of five
digits or more carry a thin space, the paper's number format; the quartiles
are printed to four significant figures.

Run without ``python -I``, like the other table scripts.
"""

import csv
import math
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "sweeps" / "amplification_form" / "results" / "seed_fit_ratio.csv"
TARGET = HERE / "tables" / "seed-fit-ratio.tex"
BAND_LABEL = {"A1": "B1", "A2": "B2"}
ORDERS = 32


def count(value):
    text = str(int(value))
    if len(text) < 5:
        return text
    groups = []
    while len(text) > 3:
        groups.insert(0, text[-3:])
        text = text[:-3]
    groups.insert(0, text)
    return r"\,".join(groups)


def quartile(value):
    """Four significant figures, fixed point for this table's range."""
    value = float(value)
    if value == 0.0:
        return "0"
    digits = 3 - int(math.floor(math.log10(abs(value))))
    return "%.*f" % (max(digits, 0), value)


def main():
    with open(SOURCE, newline="") as handle:
        rows = list(csv.DictReader(handle))
    by_band = {"A1": {}, "A2": {}}
    for row in rows:
        band = row["band"]
        if band not in by_band:
            raise SystemExit("unexpected band " + band)
        key = row["order"] if row["order"] == "all" else int(row["order"])
        by_band[band][key] = row

    lines = [
        "% generated by make_seed_fit_ratio.py from",
        "% sweeps/amplification_form/results/seed_fit_ratio.csv",
    ]
    pooled = {}
    for band, name in (("A1", "B1"), ("A2", "B2")):
        data = by_band[band]
        orders = [n for n in range(1, ORDERS + 1) if int(data[n]["cells"]) > 0]
        if band == "A1" and orders[-1] != 16:
            raise SystemExit("B1 should stop at order 16")
        if band == "A2" and len(orders) != ORDERS:
            raise SystemExit("B2 should have every order")
        total = sum(int(data[n]["cells"]) for n in orders)
        if total != int(data["all"]["cells"]):
            raise SystemExit("%s: order cells %d, pooled %d"
                             % (name, total, int(data["all"]["cells"])))
        for n in orders:
            row = data[n]
            lines.append(" & ".join([
                name, str(n), count(row["cells"]),
                quartile(row["q25"]), quartile(row["median"]),
                quartile(row["q75"]),
            ]) + r"\\")
        row = data["all"]
        lines.append(" & ".join([
            name, "all", count(row["cells"]),
            quartile(row["q25"]), quartile(row["median"]),
            quartile(row["q75"]),
        ]) + r"\\")
        if band == "A1":
            lines.append(r"\midrule")
        pooled[name] = (int(row["cells"]), row["q25"], row["median"], row["q75"])
    lines.append("")

    for row in rows:
        infinite = row["infinite"].strip()
        if infinite not in ("", "0"):
            raise SystemExit("a cell has an infinite ratio: " + str(row))

    TARGET.write_text("\n".join(lines))
    print("wrote", TARGET)
    for name in ("B1", "B2"):
        cells, q25, median, q75 = pooled[name]
        print("%s %d cells q25 %s median %s q75 %s"
              % (name, cells, q25, median, q75))


if __name__ == "__main__":
    main()
