#!/usr/bin/env python3
"""Rewrite the four per-(band, metric) order tables as one long-format table.

The sweep's CSV tree is not beside the manuscript, so this script reads the four
already-generated tables and copies every printed value across unchanged: it
splits each row on the cell separator and re-lays it out with a band column and
a metric column. Nothing is reformatted, rounded or recomputed.

Run: python merge_per_order.py
"""

import os

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables")

# (file stem, band label, metric label), in the order the groups are printed.
GROUPS = [
    ("per-order-A1-abs", "B1", "absolute"),
    ("per-order-A1-rel", "B1", "relative"),
    ("per-order-A2-abs", "B2", "absolute"),
    ("per-order-A2-rel", "B2", "relative"),
]


def data_rows(stem):
    path = os.path.join(OUT, stem + ".tex")
    with open(path) as handle:
        lines = handle.read().splitlines()
    out = []
    for line in lines:
        if "&" not in line or "\\\\" not in line:
            continue
        cells = [c.strip() for c in line.rstrip().rstrip("\\").split("&")]
        if len(cells) != 6 or not cells[0].isdigit():
            continue
        # cells: n, recursed worst, recursed at-x, direct worst, direct at-x, ratio
        out.append(cells)
    assert len(out) == 33, (stem, len(out))
    return out


def main():
    lines = ["% generated by merge_per_order.py from the four per_order tables;",
             "% every printed value is carried across unchanged"]
    for index, (stem, band, metric) in enumerate(GROUPS):
        if index:
            lines.append("\\midrule")
        for cells in data_rows(stem):
            lines.append("%s & %s & %s\\\\" % (band, metric, " & ".join(cells)))
    with open(os.path.join(OUT, "per-order.tex"), "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote per-order")


if __name__ == "__main__":
    main()
