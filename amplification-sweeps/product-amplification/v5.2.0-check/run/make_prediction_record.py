#!/usr/bin/env python3
"""Emit the per-order prediction record table from the analysis's own CSV.

Every number is read from

    sweeps/amplification_form/results/prediction_record.csv

and formatted, never retyped. The table prints, for each band, metric and
order, the recursed model's band maximum and the argument at which it is
attained, the direct model's band maximum and its argument, the band maximum
of the accumulated-arithmetic term, the state, the measured winner, and
whether the commitment is right. The state names the commitment: recursed,
direct, or an abstention.

The measurement files name the bands A1/A2; the manuscript prints them B1/B2.
The entries are named ship/product in the analysis and recursed/direct in the
paper.

Run:  python make_prediction_record.py
"""

import csv
from pathlib import Path

HERE = Path(__file__).resolve().parent
BASE = HERE / "sweeps" / "amplification_form" / "results"
OUT = HERE / "tables"

BAND_LABEL = {"A1": "B1", "A2": "B2"}
ENTRY = {"ship": "recursed", "product": "direct", "tie": "tie", "abstain": "abstain"}


def sci(text):
    """Six significant figures, the format the record prints."""
    return "%.6g" % float(text)


def argument(text):
    """Shortest spelling of the argument's double, as the record stores it."""
    return repr(float(text))


def main():
    with open(BASE / "prediction_record.csv", newline="") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != 132:
        raise SystemExit("expected 132 prediction rows, found %d" % len(rows))

    lines = [
        "% generated by make_prediction_record.py from",
        "% sweeps/amplification_form/results/prediction_record.csv",
    ]
    for row in rows:
        state = row["state"]
        if state == "abstain":
            right = "---"
        else:
            right = "yes" if row["right_where_committed"] == "1" else "no"
        lines.append(
            " & ".join(
                [
                    BAND_LABEL[row["band"]],
                    row["metric"],
                    row["order"],
                    sci(row["predicted_ship"]),
                    argument(row["predicted_ship_at_x"]),
                    sci(row["predicted_product"]),
                    argument(row["predicted_product_at_x"]),
                    sci(row["arithmetic"]),
                    ENTRY[state],
                    ENTRY[row["measured_winner"]],
                    right,
                ]
            )
            + r"\\"
        )

    OUT.mkdir(exist_ok=True)
    (OUT / "prediction-record.tex").write_text(
        "\n".join(lines) + "\n", encoding="ascii"
    )
    print("wrote tables/prediction-record.tex: %d rows" % len(rows))


if __name__ == "__main__":
    main()
