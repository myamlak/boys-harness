#!/usr/bin/env python3
"""Emit the held-out score table of the main text.

Reads

    sweeps/held-out/results/prediction_heldout.csv

one row per band, metric and order, with the frozen rule's state, its choice
and whether the choice matched the measured winner.  The table reports, per
band and metric, the commitments, how many were right, how many wrong and how
many comparisons the rule abstained on, then the total over all 132.

Writes ``tables/heldout-score.tex``, the body rows of the table in
Section 5.7 of the main text, and ``tables/heldout-commitments.tex``, the 58
commitments with the model's two band maxima and the arithmetic term, printed
in Section S17 of the supplement.

The assertions are the record's own: four groups of 33, no wrong commitment,
the groups summing to 58 commitments and 74 abstentions, and the instrument
reproducing the paper's own second-sweep score before it is used.  A change in
any of these stops the run rather than printing a different table.

Run without ``python -I``, like the other table scripts.
"""

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = (HERE / "sweeps" / "held-out" / "results"
          / "prediction_heldout.csv")
TARGET = HERE / "tables" / "heldout-score.tex"
COMMITMENTS = HERE / "tables" / "heldout-commitments.tex"
GROUPS = (("A1", "absolute", "B1"), ("A1", "relative", "B1"),
          ("A2", "absolute", "B2"), ("A2", "relative", "B2"))
ORDERS = 33


def sci(text):
    return "%.6g" % float(text)


def argument(text):
    return repr(float(text))


def main():
    with open(SOURCE, newline="") as handle:
        rows = list(csv.DictReader(handle))
    if len(rows) != len(GROUPS) * ORDERS:
        raise SystemExit("expected 132 rows, found %d" % len(rows))
    lines = []
    totals = {"commits": 0, "right": 0, "wrong": 0, "abstains": 0}
    for band, metric, label in GROUPS:
        group = [row for row in rows
                 if row["band"] == band and row["metric"] == metric]
        if len(group) != ORDERS:
            raise SystemExit("%s %s: %d rows" % (band, metric, len(group)))
        commits = [row for row in group if row["state"] != "abstain"]
        right = sum(1 for row in commits
                    if row["right_where_committed"].strip() == "1")
        abstains = len(group) - len(commits)
        wrong = len(commits) - right
        if wrong:
            raise SystemExit("%s %s: %d wrong commitments"
                             % (band, metric, wrong))
        lines.append(" & ".join([label, metric, str(len(commits)),
                                 str(right), str(wrong), str(abstains)])
                     + r"\\")
        totals["commits"] += len(commits)
        totals["right"] += right
        totals["wrong"] += wrong
        totals["abstains"] += abstains
    if totals != {"commits": 58, "right": 58, "wrong": 0, "abstains": 74}:
        raise SystemExit("totals changed: " + str(totals))
    if sorted({row["choice"] for row in rows if row["choice"]}) != [
            "direct", "recursed"]:
        raise SystemExit("unexpected choice labels")

    body = ["% generated by make_heldout_score.py from",
            "% sweeps/held-out/results/prediction_heldout.csv"]
    body.extend(lines[:2])
    body.append(r"\midrule")
    body.extend(lines[2:])
    body.append(r"\midrule")
    body.append(" & ".join(["all", "", str(totals["commits"]),
                            str(totals["right"]), str(totals["wrong"]),
                            str(totals["abstains"])]) + r"\\")
    # A row's trailing \\ at the end of an \input file does not terminate the
    # row for a \bottomrule in the parent: the lookahead starts a new row
    # instead, and \relax cannot stop it for the same reason.  The rule is
    # therefore printed in the file that ends with the row.
    body.append(r"\bottomrule")
    body.append("")
    TARGET.write_text("\n".join(body))

    commitments = [row for row in rows if row["state"] != "abstain"]
    if len(commitments) != 58:
        raise SystemExit("expected 58 commitment rows, found %d"
                         % len(commitments))
    COMMITMENTS.write_text("\n".join(
        ["% generated by make_heldout_score.py from",
         "% sweeps/held-out/results/prediction_heldout.csv"]
        + [" & ".join([
            {"A1": "B1", "A2": "B2"}[row["band"]],
            row["metric"], row["order"],
            sci(row["predicted_recursed"]),
            argument(row["predicted_recursed_at_x"]),
            sci(row["predicted_direct"]),
            argument(row["predicted_direct_at_x"]),
            sci(row["arithmetic"]),
            row["choice"], row["measured_winner"],
        ]) + r"\\" for row in commitments]
    ) + "\n")
    print("wrote", TARGET)
    print("wrote", COMMITMENTS)
    print("commits %(commits)d, right %(right)d, wrong %(wrong)d, "
          "abstains %(abstains)d" % totals)


if __name__ == "__main__":
    sys.exit(main())
