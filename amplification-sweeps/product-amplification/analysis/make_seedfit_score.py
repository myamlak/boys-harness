#!/usr/bin/env python3
"""Emit the seed-spliced score table of the main text.

Reads

    sweeps/seed-spliced/results/per_order.csv

one row per band, metric and order, with the seed term the splice predicts
from, the measured direct worst and the measured spliced worst.  The table
reports, per band and metric, how many comparisons the seed term orders and
how many it orders correctly, then the total over orders 1 to 32.  Order 0 is
structural (A_0 = 1 makes the comparison an identity) and those four rows are
excluded, so the total is 128.

Writes ``tables/seedfit-score.tex``, the body rows of the table in
Section 5.4 of the main text, and ``tables/seedfit-misses.tex``, the nine
rows the seed term orders incorrectly, printed in Section S16 of the
supplement.

The assertions are the record's own: every group has 32 comparisons at orders
1 to 32, no row is a tie, the groups sum to 128 ordered and 119 correct, and
B1 is correct at every comparison in both metrics.  A change in any of these
stops the run rather than printing a different table.

Run without ``python -I``, like the other table scripts.
"""

import csv
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
SOURCE = HERE / "sweeps" / "seed-spliced" / "results" / "per_order.csv"
TARGET = HERE / "tables" / "seedfit-score.tex"
MISSES = HERE / "tables" / "seedfit-misses.tex"
GROUPS = (("A1", "absolute", "B1"), ("A1", "relative", "B1"),
          ("A2", "absolute", "B2"), ("A2", "relative", "B2"))
ORDERS = 32


def sci(text):
    return "%.6g" % float(text)


def main():
    with open(SOURCE, newline="") as handle:
        rows = list(csv.DictReader(handle))
    scored = [row for row in rows if 1 <= int(row["order"]) <= ORDERS]
    if len(scored) != len(GROUPS) * ORDERS:
        raise SystemExit("expected %d scored rows, found %d"
                         % (len(GROUPS) * ORDERS, len(scored)))
    lines = []
    total_ordered = total_right = 0
    for band, metric, label in GROUPS:
        group = [row for row in scored
                 if row["band"] == band and row["metric"] == metric]
        if len(group) != ORDERS:
            raise SystemExit("%s %s: %d rows" % (band, metric, len(group)))
        ordered = sum(1 for row in group if row["state"] == "ordered")
        right = sum(1 for row in group
                    if row["right_where_ordered"].strip() == "1")
        if ordered != ORDERS:
            raise SystemExit("%s %s: %d ordered of %d"
                             % (band, metric, ordered, ORDERS))
        if label == "B1" and right != ORDERS:
            raise SystemExit("%s %s: %d right, expected every one"
                             % (band, metric, right))
        lines.append(" & ".join([label, metric, str(ordered), str(right)])
                     + r"\\")
        total_ordered += ordered
        total_right += right
    if (total_ordered, total_right) != (128, 119):
        raise SystemExit("sum %d ordered, %d right, expected 128, 119"
                         % (total_ordered, total_right))
    misses = [row for row in scored if row["right_where_ordered"].strip() == "0"]
    if len(misses) != 9:
        raise SystemExit("expected nine misses, found %d" % len(misses))
    if {row["band"] for row in misses} != {"A2"}:
        raise SystemExit("a miss outside A2")

    body = ["% generated by make_seedfit_score.py from",
            "% sweeps/seed-spliced/results/per_order.csv"]
    body.extend(lines[:2])
    body.append(r"\midrule")
    body.extend(lines[2:])
    body.append(r"\midrule")
    body.append(" & ".join(["all", "", str(total_ordered), str(total_right)])
                + r"\\")
    # A row's trailing \\ at the end of an \input file does not terminate the
    # row for a \bottomrule in the parent: the lookahead starts a new row
    # instead, and \relax cannot stop it for the same reason.  The rule is
    # therefore printed in the file that ends with the row.
    body.append(r"\bottomrule")
    body.append("")
    TARGET.write_text("\n".join(body))

    MISSES.write_text("\n".join(
        ["% generated by make_seedfit_score.py from",
         "% sweeps/seed-spliced/results/per_order.csv"]
        + [" & ".join([
            {"A1": "B1", "A2": "B2"}[row["band"]],
            row["metric"], row["order"],
            sci(row["seed_term"]), sci(row["direct_worst"]),
            sci(row["spliced_worst"]),
        ]) + r"\\" for row in misses] + [r"\bottomrule"]
    ) + "\n")
    print("wrote", TARGET)
    print("wrote", MISSES)
    print("ordered %d, right %d, misses %d" % (total_ordered, total_right,
                                               len(misses)))


if __name__ == "__main__":
    sys.exit(main())
