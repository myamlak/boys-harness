#!/usr/bin/env python3
"""Emit the manuscript's tables from the measurement tree's own CSV files.

Every number in a generated table is read from the file named below and is
formatted, never retyped. Argument columns use the shortest decimal spelling
that round-trips to the measured double, so a reader can reconstruct the
argument exactly.

Source tree: the sweep described in SWEEP.md (9353 arguments, 33 orders).
Run:  python make_tables.py
"""

import csv
import os

TREE = os.environ.get(
    "BOYS_SWEEP_TREE", r"C:\Users\myaml\dev\_boys_product_amplification"
)
SOURCE = os.path.join(TREE, "results")
OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "tables")

NMAX = 32

# The measurement files name the bands A1/A2; the manuscript prints them B1/B2.
BAND_LABEL = {"A1": "B1", "A2": "B2"}


def rows(name, where=None):
    with open(os.path.join(where or SOURCE, name), newline="") as handle:
        return list(csv.DictReader(handle))


def num(text):
    """Shortest spelling of the double, matching the source files' format."""
    return repr(float(text))


def sci(text):
    """Six significant figures, the format the source files print."""
    return "%.6g" % float(text)


def per_order_table(band, column, stem):
    """One (band, metric) pair of worst-per-order columns, shipped beside direct."""
    by = {}
    for row in rows("per_order.csv"):
        by[(row["band"], int(row["n"]), row["method"])] = row

    at = "at_x_abs" if column == "worst_abs" else "at_x_rel"
    lines = [
        "% generated by make_tables.py from results/per_order.csv",
        "\\begin{tabular}{rllrllr}",
        "\\toprule",
        "$n$ & \\multicolumn{2}{c}{recursed} & \\multicolumn{2}{c}{direct} & ratio\\\\",
        "\\cmidrule(lr){2-3}\\cmidrule(lr){4-5}",
        " & worst & at $x$ & worst & at $x$ &\\\\",
        "\\midrule",
    ]
    for n in range(NMAX + 1):
        ship = by[(band, n, "ship")]
        prod = by[(band, n, "product")]
        ship_v = float(ship[column])
        prod_v = float(prod[column])
        if prod_v > 0.0:
            ratio = "%.4g" % (ship_v / prod_v)
        else:
            ratio = "--"
        lines.append(
            "%2d & %s & %s & %s & %s & %s\\\\"
            % (
                n,
                sci(ship_v),
                num(ship[at]),
                sci(prod_v) if prod_v > 0.0 else "0",
                num(prod[at]),
                ratio,
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    with open(os.path.join(OUT, stem + ".tex"), "w") as handle:
        handle.write("\n".join(lines))
    print("wrote", stem)


def band_table():
    """The band-level worst of each evaluation and the ratio of the two."""
    labels = {"absolute": "absolute", "relative": "relative"}
    lines = [
        "% generated by make_tables.py from results/band_summary.csv",
        "\\begin{tabular}{llrllr}",
        "\\toprule",
        "band & metric & recursed worst & at $(n,x)$ & direct worst & at $(n,x)$\\\\",
        "\\midrule",
    ]
    for row in rows("band_summary.csv"):
        lines.append(
            "%s & %s & %s & $(%d,\\ %s)$ & %s & $(%d,\\ %s)$\\\\"
            % (
                BAND_LABEL[row["band"]],
                labels[row["metric"]],
                sci(row["ship_worst"]),
                int(row["ship_at_n"]),
                num(row["ship_at_x"]),
                sci(row["prod_worst"]),
                int(row["prod_at_n"]),
                num(row["prod_at_x"]),
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    with open(os.path.join(OUT, "band-level.tex"), "w") as handle:
        handle.write("\n".join(lines))

    # The two ratios of band worsts, and the largest single-cell ratio.
    lines = [
        "% generated by make_tables.py from results/band_summary.csv",
        "\\begin{tabular}{llrrr}",
        "\\toprule",
        "band & metric & ratio of band worsts & largest per-cell ratio & at $(n,x)$\\\\",
        "\\midrule",
    ]
    for row in rows("band_summary.csv"):
        lines.append(
            "%s & %s & %s & %s & $(%d,\\ %s)$\\\\"
            % (
                BAND_LABEL[row["band"]],
                labels[row["metric"]],
                "%.4g" % float(row["ratio_of_band_worsts"]),
                "%.5g" % float(row["max_cell_ratio"]),
                int(row["max_cell_n"]),
                num(row["max_cell_x"]),
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    with open(os.path.join(OUT, "band-ratios.tex"), "w") as handle:
        handle.write("\n".join(lines))
    print("wrote band-level, band-ratios")


def gain_table():
    """The documented downward gain beside the measured upward gain per order."""
    documented = {}
    for row in rows("documented.csv", where=os.path.join(TREE, "data")):
        documented[int(row["n"])] = row

    up = {}
    for row in rows("gain_up.csv"):
        up[(row["band"], int(row["n"]))] = row

    lines = [
        "% generated by make_tables.py from results/gain_up.csv and documented.csv",
        "\\begin{tabular}{rrrrrr}",
        "\\toprule",
        "$n$ & documented $w$ & measured $B_1$ gain & at $x$ & measured $B_2$ gain & at $x$\\\\",
        "\\midrule",
    ]
    for n in range(NMAX + 1):
        a1 = up[("A1", n)]
        a2 = up[("A2", n)]
        a1g = float(a1["worst_gain_over_x"])
        a2g = float(a2["worst_gain_over_x"])
        lines.append(
            "%2d & %s & %s & %s & %s & %s\\\\"
            % (
                n,
                sci(documented[n]["w_at_band_right_end"]),
                ("%.6g" % a1g) if a1g >= 0.0 else "--",
                num(a1["at_x"]) if a1g >= 0.0 else "--",
                ("%.6g" % a2g) if a2g >= 0.0 else "--",
                num(a2["at_x"]) if a2g >= 0.0 else "--",
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    with open(os.path.join(OUT, "gain.tex"), "w") as handle:
        handle.write("\n".join(lines))
    print("wrote gain")


def growth_table():
    """The delivered error's growth over its own order-0 value, per order."""
    grow = {}
    for row in rows("growth.csv"):
        grow[(row["band"], int(row["n"]))] = row

    lines = [
        "% generated by make_tables.py from results/growth.csv",
        "\\begin{tabular}{rrrrr}",
        "\\toprule",
        "$n$ & $B_1$ growth & at $x$ & $B_2$ growth & at $x$\\\\",
        "\\midrule",
    ]
    for n in range(NMAX + 1):
        a1 = grow[("A1", n)]
        a2 = grow[("A2", n)]
        a1g = float(a1["worst_err_ratio_ship_n_over_ship_0"])
        a2g = float(a2["worst_err_ratio_ship_n_over_ship_0"])
        lines.append(
            "%2d & %s & %s & %s & %s\\\\"
            % (
                n,
                ("%.6g" % a1g) if a1g >= 0.0 else "--",
                num(a1["at_x"]) if a1g >= 0.0 else "--",
                ("%.6g" % a2g) if a2g >= 0.0 else "--",
                num(a2["at_x"]) if a2g >= 0.0 else "--",
            )
        )
    lines += ["\\bottomrule", "\\end{tabular}", ""]
    with open(os.path.join(OUT, "growth.tex"), "w") as handle:
        handle.write("\n".join(lines))
    print("wrote growth")


def recovered_b2_table():
    """The recovered B2 argument's 60-digit reference values and 33 cells."""
    here = os.path.dirname(os.path.abspath(__file__))
    record = os.path.join(here, "sweeps", "product_amplification")
    ref = None
    for row in rows("reference.csv", where=os.path.join(record, "data")):
        if row["band"] == "A2" and row["x"] == "5.949924076054243":
            ref = row
            break
    if ref is None:
        raise SystemExit("recovered reference row not found")
    cells = [
        row
        for row in rows("cells.csv", where=os.path.join(record, "results"))
        if row["band"] == "A2" and row["x"] == "5.9499240760542431"
    ]
    cells.sort(key=lambda row: int(row["n"]))
    if [int(row["n"]) for row in cells] != list(range(NMAX + 1)):
        raise SystemExit("recovered cells are not orders 0..32")
    lines = [
        "% generated by make_tables.py from the recovered B2 argument's",
        "% appended rows in data/reference.csv and results/cells.csv",
    ]
    for row in cells:
        n = int(row["n"])
        lines.append(
            "%d & \\texttt{%s} & \\texttt{%s} & \\texttt{%s}\\\\"
            % (n, ref["f%d" % n], row["recursed"], row["direct"])
        )
    with open(os.path.join(OUT, "recovered-b2.tex"), "w") as handle:
        handle.write("\n".join(lines) + "\n")
    print("wrote recovered-b2")


if __name__ == "__main__":
    os.makedirs(OUT, exist_ok=True)
    band_table()
    gain_table()
    growth_table()
    recovered_b2_table()
    for band in ("A1", "A2"):
        for column, stem in (
            ("worst_abs", "per-order-%s-abs" % band),
            ("worst_rel", "per-order-%s-rel" % band),
        ):
            per_order_table(band, column, stem)
